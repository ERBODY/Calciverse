  static const Map<String, String> _westernToArabicDigits = {
    '0': '٠',
    '1': '١',
    '2': '٢',
    '3': '٣',
    '4': '٤',
    '5': '٥',
    '6': '٦',
    '7': '٧',
    '8': '٨',
    '9': '٩',
  };

  static String _toArabicIndicDigits(String input) {
    final buffer = StringBuffer();
    for (final char in input.split('')) {
      buffer.write(_westernToArabicDigits[char] ?? char);
    }
    return buffer.toString();
  }

  /// Format a number according to the current locale.
  /// For Arabic, digits are converted to Arabic-Indic.
  static String formatNumber(
    String languageCode,
    num value, {
    int decimalDigits = 0,
  }) {
    final locale = languageCode == 'ar' ? 'ar' : 'en';
    final formatter = NumberFormat.currency(
      locale: locale,
      symbol: '',
      decimalDigits: decimalDigits,
    );
    var formatted = formatter.format(value).trim();
    if (languageCode == 'ar') {
      formatted = _toArabicIndicDigits(formatted);
    }
    return formatted;
  }

  /// Format a date according to the current locale.
  /// For Arabic, month/day names come from intl and digits are Arabic-Indic.
  static String formatDate(
    String languageCode,
    DateTime date, {
    String pattern = 'MMMM d, yyyy',
  }) {
    final locale = languageCode == 'ar' ? 'ar' : 'en';
    var formatted = DateFormat(pattern, locale).format(date);
    if (languageCode == 'ar') {
      formatted = _toArabicIndicDigits(formatted);
    }
    return formatted;
  }
